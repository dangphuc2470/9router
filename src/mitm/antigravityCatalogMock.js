function patchFetchAvailableModelsResponse(bodyBuffer) {
  try {
    const parsed = JSON.parse(bodyBuffer.toString("utf8"));
    if (!parsed || typeof parsed !== "object" || !parsed.models || typeof parsed.models !== "object") {
      return bodyBuffer;
    }

    const mergedModels = { ...parsed.models, ...MOCK_CATALOG.models };
    parsed.models = mergedModels;

    if (Array.isArray(MOCK_CATALOG.agentModelSorts) && MOCK_CATALOG.agentModelSorts.length > 0) {
      const sortsCopy = JSON.parse(JSON.stringify(MOCK_CATALOG.agentModelSorts));
      for (const s of sortsCopy) {
        for (const g of (s.groups || [])) {
          g.modelIds = (g.modelIds || []).filter((id) => !!mergedModels[id]);
        }
      }
      parsed.agentModelSorts = sortsCopy;
    }
    parsed.defaultAgentModelId = MOCK_CATALOG.defaultAgentModelId;

    return Buffer.from(JSON.stringify(parsed), "utf8");
  } catch {
    return bodyBuffer;
  }
}

